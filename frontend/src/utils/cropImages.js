const DEFAULT_CROP_IMAGE = '/images/crops/tomato.jpg';

// Pre-sort keys by descending length so multi-word keys match first
const SORTED_CROP_KEYS = Object.keys(CROP_IMAGES).sort((a, b) => b.length - a.length);

export function getCropImage(cropName) {
  if (!cropName) return DEFAULT_CROP_IMAGE;
  // Clean parentheses and normalize
  const clean = cropName
    .replace(/\s*\([^)]*\)/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, ' ')
    .trim();

  // 1. Exact or compound match in length-descending order
  for (const key of SORTED_CROP_KEYS) {
    if (clean.includes(key)) {
      return CROP_IMAGES[key];
    }
  }

  // 2. Word token match
  const tokens = clean.split(/\s+/).filter(Boolean);
  for (const token of tokens) {
    if (CROP_IMAGES[token]) {
      return CROP_IMAGES[token];
    }
  }

  return DEFAULT_CROP_IMAGE;
}

